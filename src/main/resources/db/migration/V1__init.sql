-- Applications that send us scan reports
CREATE TABLE application (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    repo_url    VARCHAR(500),
    owner_team  VARCHAR(100),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- One row per report received from CI
CREATE TABLE scan (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT      NOT NULL REFERENCES application (id),
    source          VARCHAR(20) NOT NULL CHECK (source IN ('OWASP', 'NPM_AUDIT')),
    status          VARCHAR(20) NOT NULL CHECK (status IN ('RECEIVED', 'PROCESSING', 'COMPLETED', 'FAILED')),
    raw_report      JSONB       NOT NULL,
    submitted_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at    TIMESTAMPTZ
);
CREATE INDEX idx_scan_application ON scan (application_id);

-- A library used by an application, e.g. log4j-core 2.14.1
CREATE TABLE dependency (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id  BIGINT       NOT NULL REFERENCES application (id),
    ecosystem       VARCHAR(10)  NOT NULL CHECK (ecosystem IN ('MAVEN', 'NPM')),
    name            VARCHAR(300) NOT NULL,
    version         VARCHAR(100) NOT NULL,
    CONSTRAINT uq_dependency UNIQUE (application_id, ecosystem, name, version)
);

-- A known vulnerability, e.g. CVE-2021-44228
CREATE TABLE cve (
    id            VARCHAR(30)  PRIMARY KEY,
    cvss_score    NUMERIC(3,1) CHECK (cvss_score BETWEEN 0 AND 10),
    severity      VARCHAR(10)  NOT NULL CHECK (severity IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    description   TEXT,
    published_at  TIMESTAMPTZ,
    fetched_at    TIMESTAMPTZ
);

-- The "ticket": this dependency has this CVE
CREATE TABLE finding (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dependency_id  BIGINT      NOT NULL REFERENCES dependency (id),
    cve_id         VARCHAR(30) NOT NULL REFERENCES cve (id),
    status         VARCHAR(20) NOT NULL DEFAULT 'OPEN'
                   CHECK (status IN ('OPEN', 'IN_PROGRESS', 'FIXED', 'ACCEPTED_RISK')),
    first_seen_at  TIMESTAMPTZ NOT NULL,
    last_seen_at   TIMESTAMPTZ NOT NULL,
    sla_due_at     TIMESTAMPTZ NOT NULL,
    fixed_at       TIMESTAMPTZ,
    assignee       VARCHAR(100),
    CONSTRAINT uq_finding UNIQUE (dependency_id, cve_id)
);
CREATE INDEX idx_finding_status_sla ON finding (status, sla_due_at);
CREATE INDEX idx_finding_cve ON finding (cve_id);